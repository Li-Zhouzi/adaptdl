def _get_profiled_speedup(app_name, epoch, num_replicas):
    assert USE_PROFILED_GOODPUT, "USE_PROFILED_GOODPUT must be True"
    # Fetch discrete goodput points for this app/epoch
    gp_dict = profiled_goodput_functions[app_name][epoch]

    # Base goodput for speedup normalization
    assert 1 in gp_dict, "1 must be in gp_dict"
    base_goodput = gp_dict[1]

    # Exact match
    if num_replicas in gp_dict:
        return gp_dict[num_replicas] / base_goodput

    # Linear interpolation between nearest keys; clamp outside range
    keys = sorted(gp_dict.keys())
    # Below range
    assert 1 <= num_replicas <= 16, "num_replicas must be between 1 and 16"

    # Find bracketing points
    lower = keys[0]
    upper = keys[-1]
    for i in range(len(keys) - 1):
        a, b = keys[i], keys[i + 1]
        if a <= num_replicas <= b:
            lower, upper = a, b
            break

    g_lower = gp_dict[lower]
    g_upper = gp_dict[upper]
    # Simple linear interpolation
    ratio = (num_replicas - lower) / (upper - lower)
    g_interp = g_lower + ratio * (g_upper - g_lower)
    return g_interp / base_goodput

